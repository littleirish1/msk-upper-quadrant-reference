import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { loadTypeScriptTree } from '../lib/loadTypeScriptTree.mjs'

const ROOT = process.cwd()
const schemas = await loadTypeScriptTree(path.join(ROOT, 'src', 'lib', 'clinical-platform', 'anatomy3dSchema.ts'), path.join(ROOT, 'src'))
const registry = schemas.anatomy3dRegistrySchema.parse(JSON.parse(fs.readFileSync(path.join(ROOT, 'ai-manager', 'clinical-platform', 'anatomy-3d', 'registry.json'), 'utf8')))
const sourceCandidateLedger = JSON.parse(fs.readFileSync(path.join(ROOT, 'ai-manager', 'clinical-platform', 'anatomy-3d', 'source-candidates.json'), 'utf8'))
assert.equal(registry.assets.length, 8)
assert.equal(new Set(registry.assets.map((asset) => asset.region)).size, 8)
assert.ok(registry.assets.every((asset) => !asset.publicEligibility && !asset.assetPath && !asset.assetHash))
assert.ok(registry.assets.every((asset) => asset.structures.length === 0), 'missing assets cannot carry invented anatomy labels')
assert.equal(registry.assets.find((asset) => asset.region === 'shoulder').plannedStructures.length, 16)
assert.ok(registry.assets.every((asset) => asset.acquisitionTasks.length === 5))
assert.ok(registry.assets.every((asset) => asset.fallback.status === 'text-only-review-placeholder' && !asset.fallback.publicEligibility))
assert.ok(registry.assets.every((asset) => asset.interactions.length === 13))
assert.ok(registry.assets.every((asset) => asset.nonVisualEquivalent.webglFallbackRequired && asset.nonVisualEquivalent.transcriptRequired))
assert.ok(registry.assets.every((asset) => asset.budgets.lazyLoadRequired && asset.budgets.unrelatedRouteBundleBytes === 0))

assert.equal(sourceCandidateLedger.authority, 'private-anatomy-3d-source-candidate-ledger')
assert.equal(sourceCandidateLedger.privateAuthoringOnly, true)
assert.equal(sourceCandidateLedger.grantsApproval, false)
assert.equal(sourceCandidateLedger.candidates.length, 3)
assert.ok(sourceCandidateLedger.candidates.every((candidate) => candidate.publicationState === 'private' && candidate.publicEligibility === false && candidate.grantsApproval === false))
assert.ok(sourceCandidateLedger.candidates.every((candidate) => candidate.repositoryAssetPath === null))
assert.ok(sourceCandidateLedger.candidates.every((candidate) => Object.values(candidate.reviews).every((state) => state === 'required')))
assert.ok(sourceCandidateLedger.candidates.flatMap((candidate) => candidate.artifacts).every((artifact) => /^[a-f0-9]{64}$/.test(artifact.sha256)))
const upstream = sourceCandidateLedger.candidates.find((candidate) => candidate.id.startsWith('candidate3d.z-anatomy.'))
assert.equal(upstream.upstream.exactArchiveMatch, true)
assert.equal(upstream.upstream.commit, '98d6780fed69fa56ee43ff5c4f2f0abe2a12c2a4')
assert.equal(upstream.licenceEvidence.status, 'verified-upstream-evidence')
assert.equal(upstream.licenceEvidence.approvalGranted, false)
const upstreamBiomechanics = sourceCandidateLedger.candidates.find((candidate) => candidate.id.startsWith('candidate3d.z-biomechanics.'))
assert.equal(upstreamBiomechanics.archive.bytes, 21644942)
assert.equal(upstreamBiomechanics.archive.sha256, '0a74b2fa3c47db925b06241fa38c89b0811e58a78ee28ec440cd460e279cf22b')
assert.equal(upstreamBiomechanics.archive.gitBlobSha1, '0a59584deaf21773ffa3acb063f2cd06f3485a98')
assert.equal(upstreamBiomechanics.upstream.exactArchiveMatch, true)
assert.equal(upstreamBiomechanics.upstream.wipIsClinicalEvidence, false)
const biomechanics = sourceCandidateLedger.candidates.find((candidate) => candidate.id.startsWith('candidate3d.biomechanics.'))
assert.equal(biomechanics.declaredDerivation.status, 'UNRESOLVED')
assert.equal(biomechanics.declaredDerivation.binaryIdentityToPinnedUpstream, false)
assert.equal(biomechanics.declaredDerivation.transformationChainDemonstrated, false)
assert.ok(biomechanics.declaredDerivation.missingInputs.length >= 7)
assert.equal(biomechanics.artifacts.filter((artifact) => artifact.kind === 'gltf-binary').length, 5)
assert.ok(biomechanics.artifacts.filter((artifact) => artifact.kind === 'gltf-binary').every((artifact) => artifact.gltf.version === 2 && artifact.gltf.dracoCompressed))
assert.equal(biomechanics.artifacts.find((artifact) => artifact.filename === 'movements.ts').declaredMovementCount, 18)

const invalid = structuredClone(registry.assets[0])
invalid.publicEligibility = true
assert.equal(schemas.anatomy3dAssetSchema.safeParse(invalid).success, false)
const invented = structuredClone(registry.assets[0])
invented.structures.push({ id: 'structure.synthetic.fixture', type: 'bone', publicLabel: 'Synthetic fixture', accessibleDescription: 'Synthetic test only.', reviewState: 'required' })
assert.equal(schemas.anatomy3dAssetSchema.safeParse(invented).success, false)

console.log('Governed anatomy 3D tests passed: 8 private slots, 3 metadata-only source candidates, 16 planned shoulder structures, 13 interactions, 0 governed assets, 0 public routes.')
await import('./test-anatomy-candidates.mjs')
